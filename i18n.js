const RU_KEYS = Object.keys(RU).sort((a, b) => b.length - a.length);

function isLetter(ch) {
  return /\p{L}/u.test(ch || "");
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function tr(value) {
  if (lang !== "ru" || typeof value !== "string") return value;
  return Object.prototype.hasOwnProperty.call(RU, value) ? RU[value] : value;
}

function getLang() { return lang; }

function rawEscape(value) {
  return String(value ?? "").replace(/[&<>"']/g, letter => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  })[letter]);
}

function ruPlural(n, one, few, many) {
  const n10 = n % 10;
  const n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return n + " " + one;
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return n + " " + few;
  return n + " " + many;
}

function applyText(text) {
  if (lang !== "ru" || !text) return text;
  for (const key of RU_KEYS) {
    if (!text.includes(key) || RU[key] === key) continue;
    const re = new RegExp("(?<![\\p{L}])" + escapeRegex(key) + "(?![\\p{L}])", "gu");
    text = text.replace(re, RU[key]);
  }
  return text;
}

function localizeHtml(html) {
  if (lang !== "ru" || typeof html !== "string") return html;
  const saved = [];
  const hold = block => {
    saved.push(block);
    return "\u0000" + (saved.length - 1) + "\u0000";
  };
  html = html.replace(/<(textarea|code)\b[^>]*>[\s\S]*?<\/\1>/gi, hold);
  html = html.replace(/<p class="journal-work">[\s\S]*?<\/p>/g, hold);
  html = html.replace(/\b(alt|aria-label|placeholder|title)="([^"]*)"/g, (match, attr, value) => attr + '="' + applyText(value) + '"');
  html = html.split(/(<[^>]+>)/).map(part => part.startsWith("<") ? part : applyText(part)).join("");
  return html.replace(/\u0000(\d+)\u0000/g, (_, index) => saved[index]);
}

