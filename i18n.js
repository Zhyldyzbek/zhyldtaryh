const languageKey = "zhyldtaryh.language";
const languageUrl = new URL(location.href);
const requestedLanguage = languageUrl.searchParams.get("lang");
let language = "ky";
try {
  const savedLanguage = localStorage.getItem(languageKey);
  if (savedLanguage === "ru") language = "ru";
} catch {
  // The URL is sufficient when browser storage is unavailable.
}
if (requestedLanguage === "ky" || requestedLanguage === "ru") language = requestedLanguage;
try {
  localStorage.setItem(languageKey, language);
} catch {
  // Language links still work with storage disabled.
}

const { plan, sources, courses } = language === "ru"
  ? { plan: russianPlan, sources: russianSources, courses: russianCourses }
  : { plan: kyrgyzPlan, sources: kyrgyzSources, courses: kyrgyzCourses };

function t(kyrgyz, values = {}) {
  const phrase = language === "ru" && Object.hasOwn(russianText, kyrgyz)
    ? russianText[kyrgyz]
    : kyrgyz;
  return phrase.replace(/\{(\w+)\}/g, (placeholder, key) => values[key] ?? placeholder);
}

function localizePage() {
  document.documentElement.lang = language;
  const description = document.querySelector('meta[name="description"]');
  description.content = t(description.content);
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = t(element.textContent);
  }
  for (const element of document.querySelectorAll("[data-i18n-label]")) {
    element.setAttribute("aria-label", t(element.getAttribute("aria-label")));
  }
}

function updateLanguageLinks() {
  for (const link of document.querySelectorAll("[data-language]")) {
    const target = new URL(location.href);
    const selected = link.dataset.language;
    target.searchParams.set("lang", selected);
    link.href = target.href;
    if (selected === language) link.setAttribute("aria-current", "true");
    else link.removeAttribute("aria-current");
  }
}

localizePage();
