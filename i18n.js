function setMeta(selector, attr, value) {
  const el = document.querySelector(selector);
  if (el) el.setAttribute(attr, value);
}

function applyChrome() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    if (el.id === "journal-link" || el.children.length) return;
    el.textContent = tr(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    el.setAttribute("aria-label", tr(el.getAttribute("data-i18n-aria")));
  });
  document.querySelectorAll("[data-set-lang]").forEach(btn => {
    btn.setAttribute("aria-pressed", btn.getAttribute("data-set-lang") === lang ? "true" : "false");
  });
  document.querySelectorAll("[data-lang-switch]").forEach(el => {
    el.setAttribute("aria-label", tr("Тил"));
  });
  const desc = tr(META_DESC);
  const title = tr(META_TITLE);
  setMeta('meta[name="description"]', "content", desc);
  setMeta('meta[property="og:description"]', "content", desc);
  setMeta('meta[property="og:title"]', "content", title);
  setMeta('meta[property="og:locale"]', "content", lang === "ru" ? "ru_RU" : "ky_KG");
  setMeta('meta[property="og:image:alt"]', "content", tr(META_ALT));
  setMeta('meta[name="twitter:title"]', "content", title);
  setMeta('meta[name="twitter:description"]', "content", desc);
  const toggle = document.querySelector(".nav-toggle");
  const label = toggle?.querySelector(".sr-only");
  if (label && toggle) label.textContent = tr(toggle.getAttribute("aria-expanded") === "true" ? "Менюну жабуу" : "Меню");
  window.CourseJournal?.refreshHeader?.();
}

